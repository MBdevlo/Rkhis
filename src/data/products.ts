// Helper to generate realistic 30d history points
const generateHistory = (pCarrefour: number, pMarjane: number, pAswak: number, pBim: number): PriceHistoryPoint[] => {
  const dates = [
    '08 Sep', '12 Sep', '16 Sep', '20 Sep', '24 Sep', '28 Sep', '02 Oct', '06 Oct', 'اليوم'
  ];
  return dates.map((d, index) => {
    return {
      date: d,
      carrefour: Number((pCarrefour + (index === dates.length - 1 ? 0 : Math.cos(index) * 0.4)).toFixed(2)),
      marjane: Number((pMarjane + (index === dates.length - 1 ? 0 : Math.sin(index) * 0.3)).toFixed(2)),
      aswak: Number((pAswak + (index === dates.length - 1 ? 0 : Math.sin(index + 1) * 0.3)).toFixed(2)),
      bim: Number((pBim + (index === dates.length - 1 ? 0 : Math.cos(index + 2) * 0.2)).toFixed(2)),
    };
  });
};

